const router = require('express').Router();
const { protect, requireAdmin } = require('../middleware/auth');
const c = require('../controllers/posts.controller');
const { checkRateWindow } = require('../utils/rateLimiter');
router.use(protect);
router.use(async (req, res, next) => {
  const media = req.path.startsWith('/media/');
  const write = !['GET', 'HEAD'].includes(req.method);
  const result = await checkRateWindow(`posts-${write ? 'write' : media ? 'media' : 'read'}`, String(req.user._id), { maxCount: write ? 80 : media ? 600 : 180, windowMs: 60000 });
  if (result.limited) return res.status(429).set('Retry-After', String(Math.ceil(result.retryAfterMs / 1000))).json({ message: 'Thao tác quá nhanh, hãy thử lại sau' });
  next();
});
router.get('/', c.list);
router.get('/resolve', c.resolve);
router.post('/', c.create);
router.get('/profiles/:author', c.profile);
router.get('/reports', requireAdmin, c.listReports);
router.get('/reports/:report/media/:media', requireAdmin, c.streamReportMedia);
router.patch('/reports/:report', requireAdmin, c.resolveReport);
router.post('/media', c.reserveMedia);
router.post('/media/:media/complete', c.completeMedia);
router.delete('/media/:media', c.discardMedia);
router.get('/media/:media', c.streamMedia);
router.get('/:id', c.get);
router.patch('/:id', c.edit);
router.delete('/:id', c.remove);
router.put('/:id/state', c.setState);
router.post('/:id/reports', c.report);
router.get('/:id/reactions', c.listReactions);
router.put('/:id/reaction', c.react);
router.get('/:id/comments', c.listComments);
router.post('/:id/comments', c.addComment);
router.get('/:id/comments/:comment', c.getComment);
router.patch('/:id/comments/:comment', c.editComment);
router.delete('/:id/comments/:comment', c.deleteComment);
router.put('/:id/comments/:comment/reaction', c.react);
module.exports = router;
